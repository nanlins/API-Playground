SUFFIX_RE = re.compile(r"(市|县|自治县|旗|自治旗|区|地区|州|盟|镇|乡)$")


def normalize_city(name: str) -> str:
    """城市名归一化：去前后缀/限定词，映射省名；无法处理返回原文"""
    if not name:
        return ""
    s = name.strip()
    for prefix in ("中华人民共和国", "中国"):
        if s.startswith(prefix):
            s = s[len(prefix):].strip()
    if s in _PROVINCE_ALIASES:
        return _PROVINCE_ALIASES[s]
    if "自治区" in s:
        for full, short in _PROVINCE_ALIASES.items():
            if full in s:
                return short
    return SUFFIX_RE.sub("", s)


def lookup_city(name: str):
    """离线查城市坐标：先试原文精确，再试归一化名；命中返回 (纬度, 经度, 展示名)，未命中返回 None"""
    if not name:
        return None
    raw = name.strip()
    if raw in CITIES:
        return CITIES[raw]
    if raw in PROVINCES:
        return PROVINCES[raw]
    key = normalize_city(raw)
    if key in CITIES:
        return CITIES[key]
    if key in PROVINCES:
        return PROVINCES[key]
    return None


